export const podcasts=picks.map(([slug,topic,title,author,showId,episodeId,description,episode,cue,guest])=>{
  const {authorUrl,image,minutes}=podcastSources[slug];
  const showUrl=`https://podcasts.apple.com/ua/podcast/id${showId}`;
  return {id:`pod-${slug}`,topic,title,author,authorUrl,showUrl,image,minutes,description,episode,cue,guest,
    episodeUrl:`${showUrl}?i=${episodeId}`,cover:`./assets/podcasts/${slug}.webp`};
});

const normalize=text=>text.normalize('NFC').toLocaleLowerCase('uk').replace(/[’‘ʼ']/gu,'');
const searchable=podcasts.map(p=>[p,normalize([p.title,p.author,p.episode,podcastTopics[p.topic]].join(' '))]);
export function filterPodcasts({query='',topic='all'}={}){
  const words=normalize(query).trim().split(/\s+/).filter(Boolean);
  return searchable.filter(([p,text])=>(topic==='all'||p.topic===topic)&&words.every(word=>text.includes(word))).map(([p])=>p);
}
