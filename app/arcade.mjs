const cards = [...starterCards, ...pairs.flatMap(([ua,ru,hint])=>[
  [ua,'ua',hint], [ru,'ru',`Українською: ${ua.toLocaleLowerCase('uk')}`],
])];
const byWord = new Map(cards.map(card=>[card[0],card]));
const concept = ([word,lang,hint])=>(lang==='ru'?hint.replace(/^Українською: /,''):word).toLocaleLowerCase('uk');
export const arcadeSize = cards.length;
export const ROUND_SIZE = 10;

/** Only deal the currently visible card; quitting a round doesn't skip unseen words. */
export function nextArcadeCard(rotation, random = Math.random) {
  const known = list=>Array.isArray(list)?list.filter(word=>byWord.has(word)):[];
  let seen = new Set(known(rotation?.seen));
  if (seen.size === cards.length) seen.clear();
  const recent = known(rotation?.recent).slice(-20);
  let pool = cards.filter(([word])=>!seen.has(word) && !recent.includes(word));
  if (!pool.length) pool=cards.filter(([word])=>!seen.has(word));

  // Balance both languages in ten-card blocks, without alternating predictably.
  const partial = seen.size % ROUND_SIZE;
  if(partial){
    const ua=[...seen].slice(-partial).filter(word=>byWord.get(word)[1]==='ua').length;
    const lang=ua>=ROUND_SIZE/2?'ru':partial-ua>=ROUND_SIZE/2?'ua':null;
    const balanced=lang?pool.filter(c=>c[1]===lang):[];
    if(balanced.length) pool=balanced;
  }
  // Don't immediately quiz the translation just disclosed in the last hint.
  const justExplained=new Set(recent.slice(-5).map(word=>concept(byWord.get(word))));
  const fresh=pool.filter(card=>!justExplained.has(concept(card)));
  if(fresh.length)pool=fresh;
  const card=pool[Math.floor(random()*pool.length)], word=card[0];
  return {card, rotation:{seen:[...seen,word], recent:[...recent,word].slice(-20)}};
}
