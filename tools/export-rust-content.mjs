import assert from 'node:assert/strict';
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {arcadeDecks} from '../app/arcade.mjs';
import {packs} from '../app/data.mjs';
import {dropWords} from '../app/minigame-data.mjs';
import {frameDecks} from '../app/minigames.mjs';

// Keep the installed app's data as the source until both clients use Rust.
// Check in deterministic exports so Cargo builds do not need Node.
const check=process.argv.includes('--check');
const root=new URL('../crates/svoie-core/content/',import.meta.url);
const banner='# Generated by tools/export-rust-content.mjs. Edit the source in app/.';
if(!check)mkdirSync(root,{recursive:true});

function write(name,rows){
  const content=[banner,...rows.map(row=>row.map(field=>{
    assert.equal(typeof field,'string',`${name}: expected a string`);
    assert.ok(!/[\t\r\n]/u.test(field)&&field!=='\\N',`${name}: unsupported field`);
    return field||'\\N';
  }).join('\t'))].join('\n')+'\n';
  const file=new URL(`${name}.tsv`,root);
  if(check)assert.ok(readFileSync(file,'utf8')===content,`${name}.tsv changed; run node tools/export-rust-content.mjs`);
  else writeFileSync(file,content);
}

for(const [level,cards] of Object.entries(arcadeDecks)){
  write(`side-${level}`,cards.map(([word,lang,hint])=>[
    word,lang,hint,(lang==='ru'?hint.replace(/^Українською: /u,''):word).toLocaleLowerCase('uk'),
  ]));
}
write('letters',dropWords.map(([word,clue,art])=>[word,clue,art??'']));
for(const [album,frames] of Object.entries(frameDecks)){
  write(`frames-${album}`,frames.map(({id,category,src,title,cue,author,meta,url,action})=>[
    id,category,src,title,cue,author??'',meta??'',url??'',action??'',
  ]));
}
write('quests',packs.flatMap((pack,i)=>pack.map((q,j)=>{
  assert.equal(pack.length,5);
  assert.equal(q.distractors.length,3);
  return [`p${i+1}-${j+1}`,q.kind,q.clue??'',q.prompt,q.correct,q.explanation,...q.distractors];
})));
