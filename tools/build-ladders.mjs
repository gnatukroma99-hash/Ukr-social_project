// Recompute puzzle minima after changing the shared dictionary. Append new
// puzzles after the 0.2.6 ones so stored record IDs and indices remain valid.
import {writeFileSync} from 'node:fs';
import {ladderPairs} from '../app/ladder-data.mjs';
import {everyday} from '../app/answer-data.mjs';
import {knownWord,ladderPath} from '../app/lexicon.mjs';

let seed=413721;
const sample=a=>a[Math.floor(((seed=(Math.imul(seed,1664525)+1013904223)>>>0)/2**32)*a.length)];
const used=new Set(Object.values(ladderPairs).flat().map(p=>[...p].sort().join('-')));
if(everyday.some(w=>!knownWord(w)))throw Error('Unknown endpoint in answer-data');
const buckets=Object.fromEntries([3,4,5,6].map(n=>[n,everyday.filter(w=>w.length===n)]));
const levelSizes={easy:180,normal:200,hard:220};
const out={};
for(const [level,pairs] of Object.entries(ladderPairs)){
  const rows=pairs.map(([a,b])=>`${a} ${b} ${ladderPath(a,b).length-1}`);
  const lenses=level==='easy'?[3]:level==='normal'?[4,4,5]:[5,6,6];
  const range=level==='easy'?[2,3]:level==='normal'?[3,5]:[4,8];
  for(let i=0;rows.length<levelSizes[level];i++){
    if(i>30000)throw Error(`Insufficient reachable pairs: ${level}`);
    const pool=buckets[lenses[rows.length%lenses.length]],a=sample(pool),b=sample(pool),id=[a,b].sort().join('-');
    if(a===b||used.has(id))continue;
    const d=(ladderPath(a,b)?.length??0)-1;
    if(d<range[0]||d>range[1])continue;
    used.add(id);rows.push(`${a} ${b} ${d}`);
  }
  out[level]=rows.join('\n');
}
writeFileSync(new URL('../app/ladder-decks.mjs',import.meta.url),'// Generated by node tools/build-ladders.mjs. Keep existing IDs stable.\nexport const ladderRows={\n'+Object.entries(out).map(([k,s])=>`  ${k}:\`${s}\``).join(',\n')+'\n};\n');
console.log('Offline ladders:',levelSizes);
