"""Build the offline 3–6 letter word bank from the MPL-1.1 Ukrainian Hunspell edition.

Usage: python tools/build-lexicon.py [directory containing uk_UA.aff and uk_UA.dic]
No Python packages required. The app and CI use the checked-in result.
"""
from collections import defaultdict
from hashlib import sha256
from pathlib import Path
import re
import sys
import unicodedata
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
REV = 'c0865a85eb67dc377f2cf8e8fe2c4fa9e53f0dcb'
BASE = f'https://raw.githubusercontent.com/LibreOffice/dictionaries/{REV}/uk_UA/'
HASH = {'uk_UA.aff':'2219dd15e9802adebc45722c60943b1472640260491af38dd3e43b07e75585e6',
        'uk_UA.dic':'2e5a9e67be63bdb089b3459addb5d71113319d13768e277bcae20f3cc1ad5a93'}
LETTERS = re.compile('[абвгґдеєжзиіїйклмнопрстуфхцчшщьюя]+')

def lines(name):
    if len(sys.argv)>1:
        data=(Path(sys.argv[1])/name).read_bytes()
    else:
        with urlopen(BASE+name,timeout=60) as response: data=response.read()
    if sha256(data).hexdigest()!=HASH[name]: raise ValueError(f'Unexpected {name}; check the pinned revision')
    return data.decode('utf-8-sig').splitlines()

def build():
    # This pinned edition has simple one-character flags and single suffix rules;
    # there are no prefixes, continuation flags, compound or forbidden-word rules.
    suffixes=defaultdict(list)
    for line in lines('uk_UA.aff'):
        parts=line.split()
        if not parts or parts[0]!='SFX' or len(parts)<5: continue
        _,flag,strip,add,condition=parts[:5]
        assert '/' not in add
        suffixes[flag].append(('' if strip=='0' else strip, '' if add=='0' else add, re.compile(f'(?:{condition})$')))
    words={n:set() for n in range(3,7)}
    for entry in lines('uk_UA.dic')[1:]:
        if not entry.strip():continue
        base,_,flags=entry.split()[0].partition('/')
        base=unicodedata.normalize('NFC',base.replace('\u0301',''))
        if not LETTERS.fullmatch(base):continue  # Do not lowercase proper names or strip punctuation.
        if len(base) in words:words[len(base)].add(base)
        for flag in flags:
            for strip,add,condition in suffixes[flag]:
                n=len(base)-len(strip)+len(add)
                if n in words and base.endswith(strip) and condition.search(base):
                    form=base[:len(base)-len(strip)]+add
                    if LETTERS.fullmatch(form):words[n].add(form)
    assert 'вішка' in words[5] and 'ґанок' in words[5]
    target=ROOT/'app/lexicon-data.mjs'
    with target.open('w',encoding='utf-8',newline='\n') as out:
        out.write('// SPDX-License-Identifier: MPL-1.1\n// Ukrainian Hunspell (dict_uk / LibreOffice), Andriy Rysin and contributors.\n')
        out.write('// Game subset generated by tools/build-lexicon.py; see assets/licenses/uk-hunspell.txt.\n')
        out.write('export const formCounts = {'+', '.join(f'{n}:{len(group)}' for n,group in words.items())+'};\n')
        out.write('export const formText = {\n')
        for n,group in words.items():
            rows=sorted(group);out.write(f'{n}:`')
            out.write('\n'.join(' '.join(rows[i:i+24]) for i in range(0,len(rows),24)))
            out.write('`,\n')
        out.write('};\n')
    print('Offline word forms by length:',{n:len(w) for n,w in words.items()})

if __name__=='__main__': build()
